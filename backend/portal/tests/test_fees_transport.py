class FeeAssignmentTests(PortalTablesTestCase):
    URL = "/api/admin-portal/fee-assignments/"

    def setUp(self):
        super().setUp()
        self.class_id = self._make_class()

    def test_single_assign_list_delete(self):
        auth = self._auth(self._admin())
        student = self._make_student("s1", class_id=self.class_id)
        structure_id = self._make_fee_structure(self.class_id)
        self._make_student("s2", class_id=self.class_id)

        resp = self.client.post(self.URL, {"fee_structure_id": structure_id, "student_id": student.id},
                                content_type="application/json", **auth)
        self.assertEqual(resp.status_code, 201)
        assign_id = resp.json()["id"]

        resp = self.client.get(self.URL, {"fee_structure_id": structure_id}, **auth)
        self.assertEqual(resp.status_code, 200)
        self.assertEqual([r["student_id"] for r in resp.json()], [student.id])
        self.assertEqual(resp.json()[0]["student_name"].strip(), "s1")

        # The second student is not assigned; deleting that id 404s.
        resp = self.client.delete(f"{self.URL}?id={assign_id + 1}", **auth)
        self.assertEqual(resp.status_code, 404)

        resp = self.client.delete(f"{self.URL}?id={assign_id}", **auth)
        self.assertEqual(resp.status_code, 200)

    def test_bulk_assign_class(self):
        auth = self._auth(self._admin())
        self._make_student("s1", class_id=self.class_id)
        self._make_student("s2", class_id=self.class_id)
        structure_id = self._make_fee_structure(self.class_id)

        resp = self.client.post(self.URL, {"fee_structure_id": structure_id, "assign_class": True},
                                content_type="application/json", **auth)
        self.assertEqual(resp.status_code, 200)
        self.assertEqual(resp.json()["count"], 2)

        # Re-running must be idempotent.
        resp = self.client.post(self.URL, {"fee_structure_id": structure_id, "assign_class": True},
                                content_type="application/json", **auth)
        self.assertEqual(resp.json()["count"], 0)

        # A student not enrolled in the class stays unassigned.
        s3 = self._make_student("s3")
        resp = self.client.get(self.URL, {"fee_structure_id": structure_id}, **auth)
        self.assertNotIn(s3.id, [r["student_id"] for r in resp.json()])

    def test_required_params(self):
        auth = self._auth(self._admin())
        resp = self.client.get(self.URL, **auth)
        self.assertEqual(resp.status_code, 400)
        resp = self.client.post(self.URL, {"student_id": 1}, content_type="application/json", **auth)
        self.assertEqual(resp.status_code, 400)


