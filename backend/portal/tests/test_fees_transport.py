TABLES_NAMED = []


def _collect_table_names():
    for ddl in TABLES:
        for line in ddl.strip().splitlines():
            s = line.strip()
            if s.startswith("CREATE TABLE IF NOT EXISTS "):
                TABLES_NAMED.append(s.replace("CREATE TABLE IF NOT EXISTS ", "").strip().split()[0])


_collect_table_names()


